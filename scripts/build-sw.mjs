import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const output = join(process.cwd(), 'out')
const basePath = (process.env.NEXT_PUBLIC_BASE_PATH ?? '').replace(/\/$/, '')
const files = await walk(output)
const assets = []
const digest = createHash('sha256')

// The social card is for crawlers, never for the user. Precaching it would
// spend 120KB of a first-run download that has to finish before anyone reaches
// a place with no cell service, on an image the app never displays.
const NEVER_PRECACHE = new Set(['sw.js', 'og-image.png'])

/**
 * Turbopack emits both halves of MapLibre's dev/production export condition,
 * and the production build only ever resolves the production half — verified by
 * recording every maplibre request a production page makes. Precaching the dev
 * twins costs 2.2MB, a fifth of an install that is all-or-nothing: every byte
 * is another chance for the whole thing to fail on a tethered phone. They stay
 * on the server, so the dev branch would still resolve if it were ever taken.
 */
const isDevBundle = (pathname) => /-dev\.[0-9a-z_]+\.mjs$/.test(pathname)

let skippedBytes = 0
for (const file of files.sort()) {
  const pathname = relative(output, file).split(sep).join('/')
  // Share cards and the pages that carry them exist for crawlers. There are
  // hundreds of them and the app never shows one.
  if (pathname.startsWith('share/') || pathname.startsWith('p/')) continue
  if (NEVER_PRECACHE.has(pathname) || pathname.endsWith('.map')) continue
  const bytes = await readFile(file)
  if (isDevBundle(pathname)) {
    skippedBytes += bytes.length
    continue
  }
  digest.update(pathname).update(bytes)
  const route = pathname === 'index.html' ? '' : pathname
  assets.push(`${basePath}/${route}`)
}

// This file's own source goes into the digest too, not only the precached
// asset bytes. Precached bytes are unchanged by a commit that only touches
// worker *logic* (retry counts, cache routing, cleanup rules) — without this,
// such a commit reuses the previous version's CACHE_NAME. The new worker then
// opens and can write into a cache an old, still-active worker depends on,
// and — worse — a failed install's cleanup can delete it.
digest.update(await readFile(fileURLToPath(import.meta.url)))
const cacheName = `dust-compass-${digest.digest('hex').slice(0, 12)}`
const shell = `${basePath}/`
const dataPrefix = `${basePath}/data/`
const source = `/* Generated by scripts/build-sw.mjs. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(assets, null, 2)};
const SHELL = ${JSON.stringify(shell)};
const DATA_PREFIX = ${JSON.stringify(dataPrefix)};
// The precached data files bundled with *this* build — a manifest of exactly
// which URLs make up one coherent data revision, so a background refresh can
// be judged complete or incomplete as a set rather than file by file. Scoped
// to .json/.geojson specifically, not just the data prefix: ATTRIBUTION.md
// and LISTINGS-ATTRIBUTION.md live alongside the data files and stay
// precached for offline credit text, but they never report a JSON
// content-type, so including them here made results.every(Boolean) below
// impossible to satisfy for any real build — live-data promotion silently
// never happened (#71).
const DATA_FILES = PRECACHE.filter((url) => url.indexOf(DATA_PREFIX) === 0 && /\\.(?:geo)?json$/.test(url));
// Deliberately not scoped to CACHE_NAME. CACHE_NAME's bytes are hashed into
// its own name specifically so that name is a promise: this exact content,
// nothing else. Writing a live-fetched file into it — even one that merely
// replaced an older, equally out-of-date file — would break that promise the
// moment the two diverge from what was actually built and tested together.
// Live data lives in its own cache that persists across worker versions.
//
// It is not one fixed cache name, though — each successful background
// refresh writes into a freshly named revision cache, and a reader is only
// ever pointed at one once every file in it is confirmed present. Promoting
// used to mean deleting the fixed 'dust-compass-live-data' cache and copying
// files into it one at a time, which left the previous complete revision
// destroyed as soon as promotion started rather than once the new one was
// actually ready — a cache write failing partway through that copy (quota,
// storage eviction, a browser crash) left neither revision complete. Here,
// the pointer switch is the only step that can make a new revision visible,
// and it is a single cache.put() of one small Response — no partial states
// for a reader to observe in between.
const LIVE_POINTER_CACHE = 'dust-compass-live-pointer';
const LIVE_REVISION_PREFIX = 'dust-compass-live-data-rev-';
const LIVE_POINTER_URL = self.location.origin + '/__dust-compass-live-revision';
// Which build's CACHE_NAME promoted the revision the pointer currently
// names. The pointer and every revision cache are deliberately preserved
// across worker activations (see above) — but a revision was fetched and
// validated by whichever build ran refreshLiveData() at the time, not
// necessarily the build now activating. Without this, a newer worker
// shipping newer bundled data activated over an older worker's still-named
// pointer and preferred that older live revision over its own freshly
// bundled, by-definition-current precache — forever, since nothing here
// ever re-examined the pointer once past activation (#72).
const LIVE_POINTER_BUILD_URL = self.location.origin + '/__dust-compass-live-revision-build';
// Refresh throttling must survive service-worker process teardown. Browsers
// are free to terminate an idle worker and later start a fresh global scope,
// so an in-memory timestamp is not a real minimum interval (#92). Keep the
// attempt timestamp beside the live pointer, stamped with this build so a
// new worker version never inherits an old build's backoff accidentally.
const LIVE_REFRESH_META_URL = self.location.origin + '/__dust-compass-live-refresh-meta';

async function notify(message) {
  const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const client of windows) client.postMessage(message);
}

// A precache that gives up on the first hiccup is the failure mode that matters
// here: the download happens on whatever connection someone has before they
// drive out, and there is no second chance once they are on playa. Each asset
// gets three attempts with backoff, and several are in flight at once so an
// 8MB install is not sixty serial round trips over a tethered phone.
const ATTEMPTS = 3;
const PARALLEL = 6;
// A hotspot that accepts the connection and never answers would otherwise park
// the install until the browser kills the worker, which looks like progress.
const REQUEST_TIMEOUT_MS = 20000;

async function store(cache, url) {
  // The cache name is a content hash of the build, so anything already in it is
  // provably the right bytes. Retrying an install must not re-download 8MB.
  if (await cache.match(url)) return;
  let failure;
  for (let attempt = 0; attempt < ATTEMPTS; attempt += 1) {
    if (attempt > 0) await new Promise((resolve) => setTimeout(resolve, 300 * Math.pow(2, attempt - 1)));
    try {
      const response = await fetch(new Request(url, {
        cache: 'reload',
        signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      }));
      if (!response.ok) throw new Error('HTTP ' + response.status);
      await cache.put(url, response);
      return;
    } catch (error) {
      failure = error;
    }
  }
  throw failure;
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    let completed = 0;
    // Whether a cache by this name already existed before this attempt
    // started. CACHE_NAME is a hash of both the precached bytes and this
    // worker's own source, so in the ordinary case a name collision with an
    // existing cache means this exact version, byte for byte, already
    // installed — most likely the currently *active* worker's own cache,
    // reopened here because the browser is retrying/reinstalling it. Deleting
    // that on failure would take down a cache other code may already be
    // depending on, which is exactly the bug this guards against.
    const preexisting = await caches.has(CACHE_NAME);
    try {
      const cache = await caches.open(CACHE_NAME);
      const queue = PRECACHE.slice();
      let failed = null;

      // Install still fails as a whole if anything is unreachable. A partial
      // cache that reported success would be a lie told at the worst moment.
      async function drain() {
        while (queue.length > 0 && failed === null) {
          const url = queue.shift();
          try {
            await store(cache, url);
          } catch (error) {
            failed = { url: url, reason: String((error && error.message) || error) };
            return;
          }
          completed += 1;
          await notify({ type: 'CACHE_PROGRESS', completed, total: PRECACHE.length });
        }
      }

      await Promise.all(Array.from({ length: Math.min(PARALLEL, queue.length) }, drain));
      if (failed !== null) throw new Error('Could not cache ' + failed.url + ': ' + failed.reason);
    } catch (error) {
      // Every failure path reports. caches.open itself throws when storage is
      // already full, and that used to leave the chip saying "Preparing
      // offline" forever — which reads as progress, not as failure.
      await notify({ type: 'CACHE_FAILED', completed, total: PRECACHE.length });
      // A half-filled cache this attempt created from nothing is never the
      // active worker's — clean it up so the next quota failure is not made
      // more likely for the one person already struggling with signal. A
      // cache that already existed before this attempt began is left alone.
      if (!preexisting) await caches.delete(CACHE_NAME);
      throw error;
    }
    // Deliberately no skipWaiting here. Taking over the moment a new version
    // finishes installing means the open tab gets reloaded underneath whoever
    // is reading it — the page renders, then renders again a second later.
    // The new worker waits, the status chip says "Update ready", and the reload
    // happens when the user asks for it.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Live data is deliberately not versioned by build by default — the
    // pointer cache and every revision cache persist across worker updates,
    // managed by refreshLiveData()'s own promotion/cleanup rather than swept
    // here as though they were one more stale precache. Surviving this sweep
    // is not the same as being safe to use, though — see the build-ownership
    // check just below.
    const names = await caches.keys();
    await Promise.all(
      names
        .filter((name) => name.startsWith('dust-compass-') && name !== CACHE_NAME && name !== LIVE_POINTER_CACHE && !name.startsWith(LIVE_REVISION_PREFIX))
        .map((name) => caches.delete(name)),
    );

    // A pointer left by some other build was fetched and validated against
    // that build's own code, not this one's — so rather than compare
    // revision timestamps against a value this file has no other notion of,
    // clear it outright once ownership doesn't match and let this worker's
    // own next successful refresh repopulate and re-stamp it (#72). Until
    // then, reads fall through to fromCache()'s own bundled precache, which
    // is always current for whichever build is actually running.
    if (await caches.has(LIVE_POINTER_CACHE)) {
      const pointer = await caches.open(LIVE_POINTER_CACHE);
      const buildMarker = await pointer.match(LIVE_POINTER_BUILD_URL);
      const promotedBy = buildMarker ? await buildMarker.text() : null;
      const refreshMarker = await pointer.match(LIVE_REFRESH_META_URL);
      let refreshedBy = null;
      if (refreshMarker) {
        try {
          refreshedBy = JSON.parse(await refreshMarker.text()).build || null;
        } catch {
          refreshedBy = null;
        }
      }
      // A failed refresh may have written only refresh metadata, with no live
      // pointer/build marker yet. Treat either marker as ownership evidence so
      // same-build metadata survives, while a genuinely new build starts fresh.
      const ownedByThisBuild = promotedBy === CACHE_NAME || refreshedBy === CACHE_NAME;
      if (!ownedByThisBuild) {
        await caches.delete(LIVE_POINTER_CACHE);
        const staleRevisions = names.filter((name) => name.startsWith(LIVE_REVISION_PREFIX));
        await Promise.all(staleRevisions.map((name) => caches.delete(name)));
      }
    }

    await self.clients.claim();
    await notify({ type: 'OFFLINE_READY', total: PRECACHE.length });
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') void self.skipWaiting();
  if (event.data?.type === 'CHECK_OFFLINE_READY') event.waitUntil(verifyAndRepairPrecache());
});

/**
 * An active service-worker registration is not a cache-integrity signal:
 * Cache Storage can be evicted under storage pressure (or cleared by hand)
 * while the worker registration itself stays installed and active. A
 * returning session used to treat "some worker is active" as proof the
 * complete offline map still exists, which could claim Ready offline right
 * up until the moment a real offline launch failed to load something the UI
 * had promised was saved (#58).
 *
 * Verifies every expected PRECACHE key is actually present in this exact
 * build's cache and, if any are missing, repairs it the same way install()
 * built it in the first place — reporting through the same CACHE_PROGRESS/
 * CACHE_FAILED/OFFLINE_READY messages the page already listens for, so a
 * fully intact cache reaches Ready with nothing more than a handful of
 * cheap existence checks, and only a genuinely incomplete one pays for a
 * re-download.
 */
async function verifyAndRepairPrecache() {
  const cache = await caches.open(CACHE_NAME);
  const missing = [];
  for (const url of PRECACHE) {
    if (!(await cache.match(url))) missing.push(url);
  }
  if (missing.length === 0) {
    await notify({ type: 'OFFLINE_READY', total: PRECACHE.length });
    return;
  }
  let completed = PRECACHE.length - missing.length;
  await notify({ type: 'CACHE_PROGRESS', completed, total: PRECACHE.length });
  try {
    for (const url of missing) {
      await store(cache, url);
      completed += 1;
      await notify({ type: 'CACHE_PROGRESS', completed, total: PRECACHE.length });
    }
    await notify({ type: 'OFFLINE_READY', total: PRECACHE.length });
  } catch (error) {
    await notify({ type: 'CACHE_FAILED', completed, total: PRECACHE.length, url: String((error && error.message) || error) });
  }
}

/** Only this build's cache. An unscoped match reads other versions' caches. */
async function fromCache(request) {
  const cache = await caches.open(CACHE_NAME);
  return cache.match(request);
}

/** The revision name the pointer currently names, or undefined if none has ever promoted. */
async function currentLiveRevision() {
  const pointer = await caches.open(LIVE_POINTER_CACHE);
  const record = await pointer.match(LIVE_POINTER_URL);
  return record ? record.text() : undefined;
}

/**
 * A live-fetched data file from the currently pointed-to revision, if one
 * exists and still has this file. Falls back to the byte-for-byte build-time
 * snapshot in the precache, which is always internally consistent with the
 * app code currently running, if a live revision was never completed or the
 * current one predates this file being added to the manifest. Reads never
 * combine files from two different live revisions, because the pointer only
 * ever names one complete revision cache at a time.
 */
async function fromLiveOrPrecache(request) {
  const revisionName = await currentLiveRevision();
  if (revisionName) {
    const revision = await caches.open(revisionName);
    const cached = await revision.match(request);
    if (cached) return cached;
  }
  return fromCache(request);
}

/** Revision caches nothing points at any more — safe to reclaim now the pointer has moved on. */
async function deleteStaleRevisions(keep) {
  const names = await caches.keys();
  await Promise.all(
    names.filter((name) => name.startsWith(LIVE_REVISION_PREFIX) && name !== keep).map((name) => caches.delete(name)),
  );
}

let refreshing = null;
let lastLiveRefreshAttemptAtMemory = 0;
const LIVE_REFRESH_INTERVAL_MS = 5 * 60 * 1000;

async function persistedLiveRefreshAttemptAt() {
  try {
    const pointer = await caches.open(LIVE_POINTER_CACHE);
    const record = await pointer.match(LIVE_REFRESH_META_URL);
    if (!record) return 0;
    const metadata = JSON.parse(await record.text());
    if (metadata.build !== CACHE_NAME || !Number.isFinite(metadata.attemptedAt)) return 0;
    return metadata.attemptedAt;
  } catch {
    return 0;
  }
}

async function recordLiveRefreshAttempt(attemptedAt) {
  lastLiveRefreshAttemptAtMemory = attemptedAt;
  try {
    const pointer = await caches.open(LIVE_POINTER_CACHE);
    await pointer.put(
      LIVE_REFRESH_META_URL,
      new Response(JSON.stringify({ build: CACHE_NAME, attemptedAt })),
    );
  } catch {
    // Cache Storage itself can be unavailable/full. The in-memory timestamp
    // still prevents a hot loop for this worker lifetime; persistence resumes
    // automatically once the metadata write succeeds on a later attempt.
  }
}

async function sameResponseBytes(a, b) {
  if (!a || !b) return false;
  const [left, right] = await Promise.all([a.arrayBuffer(), b.arrayBuffer()]);
  if (left.byteLength !== right.byteLength) return false;
  const leftBytes = new Uint8Array(left);
  const rightBytes = new Uint8Array(right);
  for (let i = 0; i < leftBytes.length; i += 1) {
    if (leftBytes[i] !== rightBytes[i]) return false;
  }
  return true;
}

/**
 * The listings keep moving after a build ships — most importantly, art
 * locations become publishable when Gates open. Serve what is cached so the
 * map is instant and works offline, and refresh the *whole* data revision
 * behind the reader, one background attempt at a time.
 *
 * Every file in the manifest is fetched into a freshly named revision cache
 * before the pointer moves. Only a same-origin JSON response counts as a
 * successful fetch — a captive portal answers every request with its own
 * 200 OK login page, and it answers with HTML. Once every fetch has
 * succeeded, every expected key is confirmed present in the revision cache
 * itself (not merely inferred from the fetch results) before the pointer is
 * ever switched — a cache.put() can fail independently of a successful
 * fetch (storage quota, eviction), and that failure must never be allowed to
 * make an incomplete revision visible to a reader.
 */
function refreshLiveData() {
  if (refreshing) return refreshing;
  refreshing = (async () => {
    const now = Date.now();
    const persistedAttemptAt = await persistedLiveRefreshAttemptAt();
    const lastAttemptAt = Math.max(lastLiveRefreshAttemptAtMemory, persistedAttemptAt);
    if (now - lastAttemptAt < LIVE_REFRESH_INTERVAL_MS) return;

    // Throttle attempts, not successes. Record before touching the network so
    // a captive portal, timeout, bad JSON response, or revision cache failure
    // cannot make the very next data read immediately download the full set
    // again (#90). Cache-backed metadata keeps the same interval after the
    // browser terminates and recreates this worker global (#92).
    await recordLiveRefreshAttempt(now);

    const revisionName = LIVE_REVISION_PREFIX + now;
    let built = false;
    try {
      const responses = await Promise.all(DATA_FILES.map(async (url) => {
        try {
          const response = await fetch(url, {
            cache: 'reload',
            signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
          });
          const type = response.headers.get('content-type') || '';
          if (!response.ok || !type.includes('json')) return undefined;
          return response;
        } catch {
          return undefined;
        }
      }));

      if (responses.length > 0 && responses.every(Boolean)) {
        const current = await Promise.all(DATA_FILES.map((url) => fromLiveOrPrecache(url)));
        const unchanged = current.every(Boolean) && (
          await Promise.all(
            responses.map((response, index) => sameResponseBytes(response.clone(), current[index])),
          )
        ).every(Boolean);
        if (unchanged) {
          // A React reload caused by DATA_REFRESHED reads these files again.
          // Identical bytes are not a new revision and must not notify (or the
          // read -> refresh -> notify -> read loop never ends).
          return;
        }

        const revision = await caches.open(revisionName);
        await Promise.all(responses.map((response, index) => revision.put(DATA_FILES[index], response)));
        const matches = await Promise.all(DATA_FILES.map((url) => revision.match(url)));
        built = matches.every(Boolean);
      }
    } catch {
      built = false;
    }

    if (!built) {
      // Nothing pointed at this revision yet, so discarding it changes
      // nothing a reader can observe — the previous pointer (if any) is
      // untouched and still names a complete revision. The attempt timestamp
      // deliberately remains, providing failure backoff until the interval.
      await caches.delete(revisionName);
      return;
    }

    // The revision is complete and immutable from here on; nothing below
    // this point may delete it. The pointer write is the one atomic moment
    // a reader can start seeing it.
    const pointer = await caches.open(LIVE_POINTER_CACHE);
    await pointer.put(LIVE_POINTER_URL, new Response(revisionName));
    // Stamped alongside the pointer itself so a later activation can tell
    // whether this pointer is still this build's own to trust (#72).
    await pointer.put(LIVE_POINTER_BUILD_URL, new Response(CACHE_NAME));
    await notify({ type: 'DATA_REFRESHED' });
    await deleteStaleRevisions(revisionName);
  })().finally(() => {
    refreshing = null;
  });
  return refreshing;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  /**
   * Navigations are answered from the cache and never write to it.
   *
   * Writing them back was poisoning the precache in two ways. A captive portal
   * returns its login page with 200 OK, which then replaced the app shell
   * permanently — every later offline launch opened the Wi-Fi login screen,
   * with no way back on playa. And when a new deploy's HTML arrived but its
   * install then failed on a weak connection, the old cache was left holding
   * new HTML that names chunks which exist nowhere on the device: a blank
   * screen, unrecoverable once the server drops the old chunks.
   *
   * The shell is precached, and new versions arrive through the worker update
   * lifecycle. The network is the last resort here, not the first.
   */
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);

      // The precached shell is keyed by SHELL — a bare pathname, no query
      // string — but Cache.match(request) matches the request's full URL by
      // default. Deep links and shared locations both live at the root as
      // query params (/?poi=<uid>, /?at=<address>), not distinct paths, so
      // that exact-URL lookup misses them constantly and sends a warm,
      // fully-offline-ready install to the network for a page it already
      // has. Matching by pathname alone catches every one of those and
      // returns the cached shell with no network attempt at all — which
      // also means a captive portal's 200 OK login page never gets a chance
      // to stand in for the app on a shared link. Nothing is lost by
      // skipping the network here: the query string stays in the browser's
      // own address bar, and the app reads it from window.location once the
      // cached HTML has loaded and hydrated.
      if (url.pathname === SHELL) {
        const shell = await cache.match(SHELL);
        if (shell) return shell;
      }

      const exact = await cache.match(request);
      if (exact) return exact;

      // A listing page is a real page on the server and is deliberately not
      // precached, so it has to be fetched — but never written back, which is
      // what was poisoning the shell. Falling straight through to SHELL here
      // served the app at /p/<uid>/ with no listing in the URL, so every
      // shared link opened the bare city once a cache existed. Bounded by
      // REQUEST_TIMEOUT_MS so a captive portal or dead hotspot that never
      // answers can't hold up the eventual fallback to the cached shell.
      try {
        const network = await fetch(request, { signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS) });
        if (network.ok) return network;
      } catch {
        /* offline, timed out, or the page has gone; fall through */
      }

      // Offline, a shared listing link still has somewhere to go: the app is
      // cached, and the listing travels as a query parameter instead of a path.
      const listing = /[/]p[/]([^/]+)[/]?$/.exec(url.pathname);
      if (listing) {
        // Response.redirect() requires an absolute URL. SHELL is
        // root-relative on a project-subpath deployment (e.g.
        // "/dustcompass/"), which throws a TypeError with no base to
        // resolve it against — resolving it against the worker's own
        // origin first keeps this working for both a subpath and a
        // root-domain deployment (#75).
        const target = new URL(SHELL + '?poi=' + encodeURIComponent(listing[1]), self.location.origin);
        return Response.redirect(target.href, 302);
      }

      const shell = await cache.match(SHELL);
      if (shell) return shell;
      return fetch(request);
    })());
    return;
  }

  if (url.pathname.startsWith(DATA_PREFIX)) {
    event.respondWith((async () => {
      if (DATA_FILES.indexOf(url.pathname) === -1) {
        // Outside this build's known data manifest — not part of the
        // all-or-nothing revision, so just fetch it plainly.
        try {
          return await fetch(request);
        } catch {
          return (await fromCache(request)) || Response.error();
        }
      }
      const cached = await fromLiveOrPrecache(request);
      if (cached) {
        event.waitUntil(refreshLiveData());
        return cached;
      }
      await refreshLiveData();
      return (await fromLiveOrPrecache(request)) || fetch(request);
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await fromCache(request);
    if (cached) return cached;
    // Anything not precached — a share card, a listing page — is fetched and
    // handed straight back. Writing it into this build's cache would grow the
    // offline install with things the app never shows.
    return fetch(request);
  })());
});
`

